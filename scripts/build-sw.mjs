/**
 * Generates dist/sw.js after a production build.
 *
 * Hand-rolled rather than pulling in a PWA plugin. The requirement is "precache
 * these files and serve them with no network", which is about fifty lines of
 * worker and none of the dependencies: the plugin brought workbox with it, and
 * workbox brought six advisories in build-time packages this game never runs.
 *
 * What it replaced, and what therefore has to keep working:
 *   - precache every built file, and the start URL itself
 *   - no `skipWaiting()` on install — src/ui/updates.ts decides the moment a new
 *     build takes over, so it is never mid-journey
 *   - `clients.claim()` on activate, so the page that installed the worker is
 *     controlled by it and the `controllerchange` reload actually fires
 *   - a navigation with no network falls back to the stored page: flight mode
 *   - a `SKIP_WAITING` message activates the waiting worker on request
 */

import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';

const DIST = 'dist';

/**
 * Every cache this game makes is named with this in front, and the cleanup in
 * `activate` only ever deletes names that start with it.
 *
 * This is not tidiness. Every game in the series is published to one GitHub
 * Pages origin, and CacheStorage is per *origin*, not per scope: a worker that
 * deleted every cache but its own would take its siblings' offline copies with
 * it, and the next time one of them was opened in flight mode it would be gone.
 * src/ui/install.ts has the same origin to thank for the install bug it works
 * around.
 */
const PREFIX = 'little-engineer-';

function walk(dir) {
  const out = [];
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) out.push(...walk(full));
    else out.push(full);
  }
  return out;
}

const files = walk(DIST)
  .map((f) => relative(DIST, f).split(sep).join('/'))
  .filter((f) => f !== 'sw.js')
  .sort();

// The cache name changes whenever any asset changes, so an update replaces the
// old cache wholesale instead of serving a mix of two builds.
const hash = createHash('sha256');
for (const f of files) hash.update(f).update(readFileSync(join(DIST, f)));
const version = hash.digest('hex').slice(0, 12);

// './' is the start URL — the page a tap on the home screen icon asks for. It is
// precached alongside index.html because that is the request that has to be
// answered offline, and it is not the same string.
const precache = ['./', ...files.map((f) => `./${f}`)];

const sw = `/* Generated by scripts/build-sw.mjs. Do not edit. */
const CACHE = '${PREFIX}${version}';
const PREFIX = '${PREFIX}';
const PRECACHE = ${JSON.stringify(precache, null, 2)};

self.addEventListener('install', (event) => {
  event.waitUntil(
    // cache: 'reload' skips the browser's HTTP cache. Without it an update can
    // store the previous build's index.html — GitHub Pages lets browsers keep a
    // file for ten minutes — leaving the tablet on the old version under the new
    // worker.
    //
    // No skipWaiting() here on purpose: the new worker waits, and src/ui/updates.ts
    // sends SKIP_WAITING at a moment that interrupts nothing.
    caches.open(CACHE).then((cache) =>
      cache.addAll(PRECACHE.map((u) => new Request(u, { cache: 'reload' })))
    )
  );
});

self.addEventListener('message', (event) => {
  if (event.data && event.data.type === 'SKIP_WAITING') self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches
      .keys()
      // Only this game's own caches. The siblings on this origin keep theirs.
      .then((keys) =>
        Promise.all(keys.filter((k) => k.startsWith(PREFIX) && k !== CACHE).map((k) => caches.delete(k)))
      )
      // Take charge of the page that is already open. Without this the page that
      // installed the worker is never controlled by one, so the controllerchange
      // that reloads the app into the new build never fires for it.
      .then(() => self.clients.claim())
  );
});

/*
 * How a stored response is looked up, and why it is not the default.
 *
 * ignoreSearch, so a launch from the home screen that arrives as
 * index.html?from=somewhere still finds the page.
 *
 * ignoreVary, which is the one that cost an afternoon. The host serves these
 * files with a Vary: Origin header — vite preview does, and a CDN may. Vite marks its
 * own module script and stylesheet crossorigin, so the browser asks for those
 * two in CORS mode and send an Origin header with them; the worker's own
 * precache fetch, being same-origin, sent none. Honouring Vary therefore makes
 * those two requests — the entire game and the entire stylesheet — miss a cache
 * they are sitting in, fall through to a network that is not there, and the app
 * comes up blank with no network. Nothing here actually varies by origin: it is
 * one game serving its own files.
 */
const LOOKUP = { ignoreSearch: true, ignoreVary: true };

/*
 * Opening the game (a navigation) tries the network first, so an online launch
 * always gets the newest page; with no network, or after 3 seconds of weak
 * signal, it falls back to the stored page. Everything else is cache-first: the
 * game ships all of its content in the bundle and makes no runtime requests.
 */
function shell(request) {
  return caches.match(request, LOOKUP).then((hit) => hit || caches.match('./index.html', LOOKUP));
}

self.addEventListener('fetch', (event) => {
  const request = event.request;
  if (request.method !== 'GET') return;

  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;

  if (request.mode === 'navigate') {
    const network = fetch(request, { cache: 'no-store' }).then((r) => (r && r.ok ? r : Promise.reject(r)));
    const timeout = new Promise((_, reject) => setTimeout(reject, 3000));
    event.respondWith(Promise.race([network, timeout]).catch(() => shell(request)));
    return;
  }

  event.respondWith(
    caches.match(request, LOOKUP).then((hit) => {
      if (hit) return hit;
      return fetch(request)
        .then((response) => {
          if (response && response.status === 200 && response.type === 'basic') {
            const copy = response.clone();
            caches.open(CACHE).then((cache) => cache.put(request, copy));
          }
          return response;
        })
        .catch(() => Response.error());
    })
  );
});
`;

writeFileSync(join(DIST, 'sw.js'), sw);
console.log(`sw.js written — cache ${PREFIX}${version}, ${precache.length} entries precached`);
